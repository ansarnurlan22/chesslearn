/**
 * Returns today's puzzle dynamically based on calendar day (1 to 31).
 */
export function getTodayDailyPuzzle(date?: Date): DailyPuzzle {
  const targetDate = date || new Date();
  const day = targetDate.getDate(); // 1 to 31
  return DAILY_PUZZLES.find((p) => p.day === day) || DAILY_PUZZLES[0];
}

/**
 * Formats a date as YYYY-MM-DD for daily streak calculations.
 */
export function getDateKey(date?: Date): string {
  const d = date || new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}
